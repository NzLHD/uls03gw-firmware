#!/usr/bin/env python3
"""Gzip web/index.html into web_page.h (a C byte array) for the firmware.
Usage: gen_page.py <index.html> <web_page.h>"""
import gzip
import sys

src, dst = sys.argv[1], sys.argv[2]
raw = open(src, 'rb').read()
gz = gzip.compress(raw, compresslevel=9, mtime=0)
with open(dst, 'w') as f:
    f.write('/* generated by web/gen_page.py from web/index.html - do not edit */\n')
    f.write('#include <stdint.h>\n#include <stddef.h>\n')
    f.write('static const uint8_t WEB_PAGE_GZ[] = {\n')
    for i in range(0, len(gz), 16):
        f.write('  ' + ','.join('0x%02x' % b for b in gz[i:i + 16]) + ',\n')
    f.write('};\nstatic const size_t WEB_PAGE_GZ_LEN = %d; /* %d bytes uncompressed */\n' % (len(gz), len(raw)))
print('%s: %d bytes -> %d gzipped' % (dst, len(raw), len(gz)))
